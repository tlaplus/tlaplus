	private final Path fixture;
	private final boolean expectedValidated;
	private final boolean expectedFallback;

	public ValidatorTest(String fixture, boolean expectedValidated, boolean expectedFallback) {
		this.fixture = Paths.get(CommonTestCase.BASE_DIR, fixture);
		this.expectedValidated = expectedValidated;
		this.expectedFallback = expectedFallback;
	}

	@Test
	public void detectsUsingChecksumValidationResult() throws IOException, ParseException {
		final ParseUnit unit = parse(true);
		assertEquals(Boolean.valueOf(expectedValidated), unit.containsPlusCalAlgorithm());
		assertEquals(expectedValidated, Validator.containsAlgorithm(unit));
	}

	@Test
	public void detectsWithoutChecksumValidation() throws IOException, ParseException {
		final ParseUnit unit = parse(false);
		assertNull(unit.containsPlusCalAlgorithm());
		assertEquals(expectedFallback, Validator.containsAlgorithm(unit));
	}

	private ParseUnit parse(boolean validateTranslation) throws ParseException {
		final SpecObj spec = new SpecObj(fixture.toString(),
				new SimpleFilenameToStream(fixture.getParent().toString()));
		final RecordedSanyOutput out = new RecordedSanyOutput(LogLevel.ERROR);
		SANY.frontEndInitialize();
		SANY.frontEndParse(spec, out, new SanySettings(false, false, false, validateTranslation));
		assertTrue(out.toString(), spec.parseErrors.isSuccess());
		return spec.getRootParseUnit();
	}
