package tlc2.util;

import java.lang.invoke.MethodHandles;
import java.lang.invoke.VarHandle;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import tlc2.tool.TLCState;
import tlc2.value.IValue;
import util.UniqueString;

/** An <code>IdThread</code> is a <code>Thread</code> with an
    integer identifier. */

public class IdThread extends Thread {
	private static final ThreadLocal<TLCState> currentState = new ThreadLocal<>();
	
	/**
	 * @return null during the generation of initial states (see
	 *         tlc2.tool.ModelChecker.doInit(boolean) and a TLCState during the
	 *         generation of next-states in tlc2.tool.ModelChecker.doNext(TLCState,
	 *         ObjLongTable, Worker). It corresponds to the predecessor state of the
	 *         next-state currently being generated by the worker thread.
	 */
	public static final TLCState getCurrentState() {
		return currentState.get();
	}
	public static final void setCurrentState(final TLCState state) {
		currentState.set(state);
	}
	public static final TLCState resetCurrentState() {
		final TLCState tlcState = currentState.get();
		currentState.remove();
		return tlcState;
	}
	
    private final int id;
	// Registers are written by other threads too (TLCSet in PERIODIC, see
	// Simulator#setAllValues) and read by other threads (TLCGet("all")). Reads
	// and steady-state writes are lock-free. The lock is taken to grow the
	// array, by getLocalValues, and by a reader that runs into a sealed slot;
	// growth seals every old slot so a concurrent write is either carried over
	// to the new array or retried on it, never lost.
	private static final VarHandle SLOTS = MethodHandles.arrayElementVarHandle(Object[].class);
	private static final Object SEALED = new Object();
	private final Object localValuesLock = new Object();
	private volatile Object[] localValues = new Object[4];
	private final Map<UniqueString, IValue> namedRegisters = new ConcurrentHashMap<>();
   
    /** Create a new thread with ID <code>id</code>. */
    public IdThread(int id) {
        this.id = id;
    }
   
    public IdThread(Runnable runnable, String name, int id) {
    	super(runnable, name);
    	this.id = id;
	}

	/** Return this thread's ID. */
    // This method was originally called getId, but a later
    // version of Java introduced a getId method into the Thread
    // class which returned a long, and it doesn't allow it to be
    // overridden by a method that returns an int.  So 
    // LL changed the return type from int to long on 31 Aug 2007
    // However, apparently a later version of Java complained when
    // its use in class tlc.tool.liveness.LiveWorker assigned
    // its value to an int variable, so it was renamed myGetId.
    // It is used only in LiveWorker.
    public final int myGetId() { // getId() {
        return this.id;
    }

    /** Return the Id of the calling thread. This method
        will result in a <TT>ClassCastException</TT> if
        the calling thread is not of type <TT>IdThread</TT>. */
    public static int GetId() {
        return ((IdThread)Thread.currentThread()).id;
    }

    /** If the calling thread is of type <TT>IdThread</TT>,
        return its ID. Otherwise, return <TT>otherId</TT>. */
    public static int GetId(int otherId) {
        Thread th = Thread.currentThread();
        return (th instanceof IdThread) ? ((IdThread)th).id : otherId;
    }
    
	public IValue getLocalValue(int idx) {
		final Object[] vals = this.localValues;
		if (idx >= vals.length) {
			return null;
		}
		final Object v = SLOTS.getAcquire(vals, idx);
		if (v != SEALED) {
			return (IValue) v;
		}
		// The array is being grown. Wait for the new one, which never holds SEALED.
		synchronized (this.localValuesLock) {
			final Object[] grown = this.localValues;
			return idx < grown.length ? (IValue) SLOTS.getAcquire(grown, idx) : null;
		}
	}

	/**
	 * @return A copy of this thread's registers. The lock keeps growth from
	 *         sealing slots under the copy, but writes to existing slots are
	 *         lock-free, so the copy is not an atomic snapshot when the owner
	 *         keeps writing (see TLCGet("all") in TLC.tla).
	 */
	public IValue[] getLocalValues() {
		synchronized (this.localValuesLock) {
			final Object[] vals = this.localValues;
			final IValue[] copy = new IValue[vals.length];
			for (int i = 0; i < vals.length; i++) {
				copy[i] = (IValue) SLOTS.getAcquire(vals, i);
			}
			return copy;
		}
	}

	public void setLocalValue(int idx, IValue val) {
		while (true) {
			final Object[] vals = this.localValues;
			if (idx >= vals.length) {
				break;
			}
			final Object cur = SLOTS.getAcquire(vals, idx);
			if (cur == SEALED) {
				break;
			}
			if (SLOTS.compareAndSet(vals, idx, cur, val)) {
				return;
			}
		}
		synchronized (this.localValuesLock) {
			Object[] vals = this.localValues;
			if (idx >= vals.length) {
				final Object[] grown = new Object[idx + 1];
				for (int i = 0; i < vals.length; i++) {
					grown[i] = SLOTS.getAndSet(vals, i, SEALED);
				}
				this.localValues = grown;
				vals = grown;
			}
			SLOTS.setRelease(vals, idx, val);
		}
	}

	public IValue getNamedRegister(UniqueString name) {
		return namedRegisters.get(name);
	}

	public void setNamedRegister(UniqueString name, IValue val) {
		namedRegisters.put(name, val);
	}

	public Map<UniqueString, IValue> getNamedRegisters() {
		return namedRegisters;
	}
}
